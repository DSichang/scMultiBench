"""Rewrite the summary table at the top of each API reference page.

Every ``docs/reference/*.md`` page of the docs site opens with a table of its
``:::`` entries: the public name (the directive's ``heading:``), linked to the
object's anchor, and the summary line of its docstring. The table is derived
from the docstrings, never written by hand: edit the docstring, then run

    python tools/gen_reference_tables.py [DOCS_DIR]           # rewrite in place
    python tools/gen_reference_tables.py [DOCS_DIR] --check   # exit 1 if stale

DOCS_DIR is the site's ``docs/`` folder (default: $SCMULTIBENCH_DOCS). The
docstrings are read from the ``multibench`` this file sits next to. The table
lives between the BEGIN / END markers; a page without them gets the table
after its first paragraph. tests/test_docs_consistency.py fails when a table
misses an entry or a cell differs from its docstring.
"""
import argparse
import importlib
import inspect
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- api-summary: generated by tools/gen_reference_tables.py from the docstrings; do not edit by hand -->"
END = "<!-- /api-summary -->"


def directives(text):
    """``[(path, heading)]`` of the ``:::`` directives of one page, in page order."""
    out = []
    for m in re.finditer(r"^::: (\S+)\n((?:[ \t]+.*\n)*)", text, re.M):
        opts = dict(re.findall(r"^\s+(\w+):\s*'([^']*)'\s*$", m.group(2), re.M))
        out.append((m.group(1), opts.get("heading") or m.group(1)))
    return out


def resolve(path):
    """The object a ``:::`` path names: longest importable module prefix, then attributes."""
    parts = path.split(".")
    for k in range(len(parts), 0, -1):
        try:
            obj = importlib.import_module(".".join(parts[:k]))
        except ImportError:
            continue
        for part in parts[k:]:
            obj = getattr(obj, part)
        return obj
    raise ImportError(path)


def summary(obj):
    """The docstring's summary: its first paragraph on one line (numpydoc keeps
    it to one line, so this is the first line)."""
    doc = inspect.getdoc(obj) or ""
    return " ".join(doc.split("\n\n", 1)[0].split())


def cell(text):
    return text.replace("|", r"\|")


def table(text):
    """The marked-up summary table for one page's directives."""
    rows = [f"| [`{heading}`](#{path}) | {cell(summary(resolve(path)))} |"
            for path, heading in directives(text)]
    return "\n".join([BEGIN, '<div class="api-summary" markdown>', "",
                      "| Name | Summary |", "|---|---|", *rows,
                      "", "</div>", END])


def rewrite(text):
    """The page with its summary table regenerated (inserted after the first
    paragraph below the title when the page has none yet)."""
    new = table(text)
    if BEGIN in text:
        head, rest = text.split(BEGIN, 1)
        return head + new + rest.split(END, 1)[1]
    m = re.search(r"^# .*\n\n(?:.+\n)+", text, re.M)
    if m is None:
        raise ValueError("no title and first paragraph to put the table after")
    return text[:m.end()] + "\n" + new + "\n" + text[m.end():]


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("docs", nargs="?", default=os.environ.get("SCMULTIBENCH_DOCS"),
                    help="the docs site's docs/ folder (default: $SCMULTIBENCH_DOCS)")
    ap.add_argument("--check", action="store_true", help="report stale pages, write nothing")
    args = ap.parse_args(argv)
    if not args.docs:
        ap.error("DOCS_DIR not given and SCMULTIBENCH_DOCS not set")
    sys.path.insert(0, str(ROOT))
    stale = []
    for page in sorted((Path(args.docs) / "reference").glob("*.md")):
        text = page.read_text()
        if not directives(text):
            continue
        new = rewrite(text)
        if new != text:
            stale.append(page.name)
            if not args.check:
                page.write_text(new)
    verb = "stale" if args.check else "rewritten"
    print(f"{verb}: {', '.join(stale)}" if stale else "all reference tables up to date")
    return 1 if (args.check and stale) else 0


if __name__ == "__main__":
    sys.exit(main())
