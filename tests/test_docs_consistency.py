    gate.on_startup(command="build", dirty=False)
    assert gate.on_config(config) is config
    monkeypatch.setenv("DEPLOY_GATE", "1")                     # the rehearsal: a gated build
    with pytest.raises(Abort, match=r"nothing was built or pushed"):
        gate.on_config(config)
    monkeypatch.delenv("DEPLOY_GATE")
    gate.on_startup(command="gh-deploy", dirty=False)
    with pytest.raises(Abort, match=r"a\.ipynb: not executed"):
        gate.on_config(config)
    (site / "b.ipynb").unlink()
    _write_nb(site / "a.ipynb", cells)
    assert gate.on_config(config) is config                    # current copies deploy


