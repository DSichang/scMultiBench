"""Cheap consistency checks between the docs surfaces that live in this repo.

The notebooks are generated by tools/gen_tut.py; README/pyproject carry the
paper's title and DOI; these tests pin the facts the user study found drifting
(two install cells that disagreed, a '--no-deps' install that broke evaluate(),
two paper titles, a missing [project.urls]).
"""
import ast
import importlib.util
import json
import re
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
NOTEBOOKS = sorted((ROOT / "notebooks").glob("*.ipynb"))
PAPER_TITLE = "Multitask benchmarking of single-cell multimodal omics integration methods"
PAPER_DOI = "10.1038/s41592-025-02856-3"


def _load_gen_tut():
    spec = importlib.util.spec_from_file_location("gen_tut", ROOT / "tools" / "gen_tut.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)          # __main__ guard: nothing is written
    return mod


def _code_cells(path):
    nb = json.loads(path.read_text())
    return ["".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code"]


def test_readme_and_pyproject_share_one_paper_title_and_doi():
    readme = (ROOT / "README.md").read_text()
    assert PAPER_TITLE in readme
    assert PAPER_DOI in readme
    assert "Benchmarking single-cell multimodal data integrations" not in readme
    assert "mtb.cite(" in readme
    pyproject = (ROOT / "pyproject.toml").read_text()
    urls = pyproject.split("[project.urls]", 1)[1].split("\n[", 1)[0]
    for key in ("Repository", "Upstream", "Paper"):
        assert re.search(rf"^{key}\s*=", urls, re.M), f"[project.urls] lacks {key}"
    assert PAPER_DOI in urls


def test_notebook_install_cells_identical():
    gen = _load_gen_tut()
    install = [c.strip() for c in gen.INSTALL_CELLS]
    assert len(install) == 2
    seen = 0
    for nb in NOTEBOOKS:
        cells = _code_cells(nb)
        for c in cells:
            assert "--no-deps" not in c, f"{nb.name}: --no-deps install breaks evaluate()"
            assert "requires the conda environments" not in c, nb.name
        pip_cells = [c for c in cells if "pip -q install" in c or "pip install" in c]
        if not pip_cells:
            continue                     # executed on the host; no install cell
        seen += 1
        stripped = [c.strip() for c in cells]
        for cell in install:
            assert cell in stripped, f"{nb.name}: install cell differs from gen_tut.INSTALL_CELLS"
    assert seen >= 5                     # four tutorials + colab quickstart


@pytest.mark.parametrize("nb", NOTEBOOKS, ids=lambda p: p.name)
def test_notebook_code_cells_parse(nb):
    ipy = pytest.importorskip("IPython.core.inputtransformer2")
    tm = ipy.TransformerManager()
    for c in _code_cells(nb):
        ast.parse(tm.transform_cell(c))


def test_gen_tut_output_matches_committed_notebooks(tmp_path, monkeypatch):
    """Regenerating must reproduce the committed notebooks' code cells (no hand edits)."""
    gen = _load_gen_tut()
    import nbformat
    for cat, s in gen.SCEN.items():
        cells = [c.source for c in gen.build_tutorial(cat, s) if c.cell_type == "code"]
        committed = _code_cells(ROOT / "notebooks" / f"tutorial_{cat}.ipynb")
        assert cells == committed, f"tutorial_{cat}.ipynb is not gen_tut output - regenerate"
    cells = [c.source for c in gen.build_colab_quickstart() if c.cell_type == "code"]
    assert cells == _code_cells(ROOT / "notebooks" / "colab_quickstart.ipynb")


def test_tutorials_use_the_public_api_not_raw_csv_reads():
    gen = _load_gen_tut()
    for cat, s in gen.SCEN.items():
        src = "\n".join(c.source for c in gen.build_tutorial(cat, s) if c.cell_type == "code")
        assert "mtb.load_results(" in src
        assert "mtb.labels_for(" in src
        assert "mtb.cite(" in src
