def _write_nb(path, cells, executed=True):
    """A minimal notebook file: ``cells`` is ``[(cell_type, source), ...]``."""
    out = []
    for kind, source in cells:
        cell = {"cell_type": kind, "metadata": {}, "source": source.splitlines(keepends=True)}
        if kind == "code":
            cell.update(execution_count=1 if executed else None, outputs=[])
        out.append(cell)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps({"cells": out, "metadata": {}, "nbformat": 4, "nbformat_minor": 5}))


