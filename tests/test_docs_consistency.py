def _visible(text):
    """The page without its collapsed ``??? `` Details blocks (an indented
    block ends at the first non-blank line that is not indented)."""
    out, skip = [], False
    for line in text.splitlines():
        if line.startswith("??? "):
            skip = True
            continue
        if skip and line.strip() and not line.startswith("    "):
            skip = False
        if not skip:
            out.append(line)
    return "\n".join(out)


