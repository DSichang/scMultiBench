def test_collapsed_blocks_render_as_markdown():
    """Every ``<details>`` block in the generated notebooks has a one-line
    ``<summary>``, a blank line after it and a blank line before
    ``</details>``: without them Jupyter, Colab and mkdocs-jupyter show the
    inner markdown as literal text (``**Label.**``, ``- item``)."""
    gen = _load_gen_tut()
    n = 0
    for name in _generated(gen):
        nb = json.loads((ROOT / "notebooks" / f"{name}.ipynb").read_text())
        for c in nb["cells"]:
            src = "".join(c["source"])
            if c["cell_type"] != "markdown" or "<details>" not in src:
                continue
            assert src.count("<details>") == src.count("</details>"), name
            for block in re.findall(r"<details>(.*?)</details>", src, re.S):
                n += 1
                assert re.match(r"\n<summary>[^<\n]+</summary>\n\n\S", block), \
                    f"{name}: <summary> must be followed by a blank line: {block[:80]!r}"
                assert block.endswith("\n\n") and not block.endswith("\n\n\n"), \
                    f"{name}: one blank line before </details>: {block[-80:]!r}"
    assert n >= 20, f"only {n} collapsed blocks across the generated notebooks"


def test_tutorials_use_the_public_api_not_raw_csv_reads():
    """Stored scores come from load_results. The tutorials read no file of a
    dataset themselves: ``mtb.data.write_example`` writes the example files
    of the task's dataset, and the one kind of read the tutorials keep is the
    ``read_h5ad`` of these ``my_*.h5ad`` files in the own-data section."""
    gen = _load_gen_tut()
    for key, s in gen.TASKS.items():
        cells = gen.build_tutorial(key)
        src = "\n".join(c.source for c in cells if c.cell_type == "code")
        md = "\n".join(c.source for c in cells if c.cell_type == "markdown")
        # stored scores are drawn only where the task has a stored dataset
        assert ("mtb.load_results(" in src) == bool(s.get("stored_ds")), key
        assert "source=" not in src, key
        assert "mtb.cite(" in md
        assert f'mtb.data.write_example("{s["ds"]}")' in src, key
        assert src.count("write_example(") == 1, key
        assert 'ad.read_h5ad("my_' in src, key
        reads = re.findall(r"read_h5ad\(([^)]*)\)", src)
        assert reads, key
        for arg in reads:
            assert re.fullmatch(r'"my_\w+\.h5ad"', arg), (key, arg)
        assert "read_csv(" not in src and "read_canonical(" not in src and "h5py" not in src, key
        assert "read_csv(RESULTS" not in src and "results/" not in src
        assert "from multibench.engine import registry" not in src


